const PER_BOT_COOLDOWN = 9000;
const ROOM_GAP = 2200;

function pick(arr, rnd) { return arr[Math.floor(rnd() * arr.length)]; }

/** ท่าทีที่บอทแสดงออกตอนนี้ */
function stanceOf(g, p) {
  if (p.role === 'lord') return 'lord';
  if (p.role === 'loyalist') return 'loyal';
  const lord = g.players.find((q) => q.role === 'lord');
  if (p.role === 'rebel') return p.rebelScore >= 3 ? 'rebel' : 'fake';
  if (p.role === 'traitor') return g.alive().length <= 2 && lord && lord.alive ? 'traitor' : 'fake';
  return 'loyal';
}

function suspectFor(g, p) {
  const others = g.alive().filter((q) => q !== p && q.role !== 'lord');
  if (!others.length) return null;
  const st = stanceOf(g, p);
  if (st === 'fake') {
    // แกล้งกล่าวหาคนที่ดูบริสุทธิ์ที่สุด เพื่อเบี่ยงเบนความสนใจ
    const s = [...others].sort((a, b) => a.rebelScore - b.rebelScore)[0];
    return s;
  }
  const s = [...others].sort((a, b) => b.rebelScore - a.rebelScore)[0];
  return s.rebelScore > 0 ? s : null;
}

class Banter {
  /** @param {{rnd?:()=>number, now?:()=>number}} [o] */
  constructor(o = {}) {
    this.rnd = o.rnd || Math.random;
    this.now = o.now || Date.now;
    this.lastBy = new Map();
    this.lastAny = 0;
    this.stance = new Map();
  }

  line(g, p, key, vars = {}) {
    const st = stanceOf(g, p);
    const pool = L[key] && (L[key][st] || L[key].any || (st === 'fake' ? L[key].loyal : null));
    if (!pool || !pool.length) return null;
    const lord = g.players.find((q) => q.role === 'lord');
    return pick(pool, this.rnd).replace(/\{(\w+)\}/g, (_, k) => {
      if (k === 'lord') return lord ? lord.name : 'ฝ่าบาท';
      if (k === 'me') return p.name;
      const v = vars[k];
      return v ? v.name : '';
    });
  }

  ready(p, force) {
    const t = this.now();
    if (!force && t - (this.lastBy.get(p.pid) || 0) < PER_BOT_COOLDOWN) return false;
    if (!force && t - this.lastAny < ROOM_GAP) return false;
    return true;
  }

  say(out, g, p, key, vars, chance, force) {
    if (!p || !p.isBot || !p.alive && !['win', 'lose', 'gg'].includes(key)) return;
    if (this.rnd() > chance || !this.ready(p, force)) return;
    const text = this.line(g, p, key, vars);
    if (!text) return;
    const t = this.now();
    this.lastBy.set(p.pid, t);
    this.lastAny = t;
    out.push({ pid: p.pid, name: p.name, text });
  }

  /** เปลี่ยนท่าทีครั้งแรก (เผยตัว) → พูดประกาศ */
  checkReveal(out, g) {
    for (const p of g.players) {
      if (!p.isBot || !p.alive) continue;
      const st = stanceOf(g, p);
      const prev = this.stance.get(p.pid);
      this.stance.set(p.pid, st);
      if (prev && prev !== st) {
        if (st === 'rebel') this.say(out, g, p, 'exposedRebel', {}, 0.9, true);
        if (st === 'traitor') this.say(out, g, p, 'exposedTraitor', {}, 1, true);
      }
    }
  }

  /** @returns {{pid:string,name:string,text:string}[]} */
  react(g, ev) {
    const out = [];
    const bots = g.alive().filter((p) => p.isBot);
    const lord = g.players.find((p) => p.role === 'lord');
    const { source, target } = ev;
    const some = (list, n) => [...list].sort(() => this.rnd() - 0.5).slice(0, n);
    this.checkReveal(out, g);
    switch (ev.type) {
      case 'start':
        for (const p of some(bots, 2)) this.say(out, g, p, 'start', {}, 0.8, true);
        break;
      case 'turn': {
        const p = ev.player;
        if (!p.isBot) break;
        const x = suspectFor(g, p);
        if (x && this.rnd() < 0.5) this.say(out, g, p, 'accuse', { x }, 0.45);
        else this.say(out, g, p, 'idle', {}, 0.3);
        break;
      }
      case 'attack':
        if (source && source.isBot) {
          if (target.role === 'lord') this.say(out, g, source, 'iAttackLord', { t: target }, 0.5);
          else this.say(out, g, source, 'iAttack', { t: target }, 0.3);
        }
        if (target.isBot) this.say(out, g, target, 'attacked', { s: source }, 0.55);
        if (target.role === 'lord' && source && source.role !== 'lord') {
          const watcher = some(bots.filter((p) => p !== source && p !== target), 1)[0];
          if (watcher) this.say(out, g, watcher, 'lordAttacked', { s: source }, 0.45);
        }
        break;
      case 'damage':
        if (target.isBot) this.say(out, g, target, 'hurt', { s: source }, 0.2);
        if (target.role === 'lord' && target.hp === 1) {
          this.say(out, g, target, 'lordLow', {}, 0.7);
          const w = some(bots.filter((p) => p !== target), 1)[0];
          if (w) this.say(out, g, w, 'lordLow', {}, 0.5);
        }
        break;
      case 'dying':
        if (target.isBot) this.say(out, g, target, 'dying', {}, 0.85, true);
        break;
      case 'saved':
        if (target.isBot) this.say(out, g, target, 'savedMe', { s: source }, 0.75, true);
        if (source.isBot) this.say(out, g, source, 'iSaved', { t: target }, 0.3);
        break;
      case 'death': {
        const killedLoyalByLord = target.role === 'loyalist' && source && source.role === 'lord';
        if (source && source.isBot && source.alive && source !== target) this.say(out, g, source, 'myKill', { t: target }, 0.5);
        const key = killedLoyalByLord ? 'lordKilledLoyal'
          : target.role === 'rebel' ? 'deathRebel' : target.role === 'loyalist' ? 'deathLoyal' : target.role === 'traitor' ? 'deathTraitor' : null;
        if (key) for (const p of some(bots.filter((q) => q !== target && q !== source), 2)) this.say(out, g, p, key, { t: target }, 0.6, true);
        break;
      }
      case 'negated':
        if (target && target.isBot) this.say(out, g, target, 'negated', { s: source }, 0.4);
        break;
      case 'robbed':
        if (target.isBot) this.say(out, g, target, 'robbed', { s: source }, 0.35);
        break;
      case 'indulgence':
        if (target.isBot) this.say(out, g, target, 'indulged', { s: source }, 0.55);
        break;
      case 'lightning':
        if (target.isBot) this.say(out, g, target, 'lightning', {}, 0.8, true);
        break;
      case 'gameover': {
        const winners = new Set((ev.result && ev.result.winners) || []);
        for (const p of some(g.players.filter((q) => q.isBot), 3)) {
          this.say(out, g, p, winners.has(p.pid) ? 'win' : 'lose', {}, 0.9, true);
        }
        const gg = some(g.players.filter((q) => q.isBot), 1)[0];
        if (gg) this.say(out, g, gg, 'gg', {}, 0.7, true);
        break;
      }
      default:
        break;
    }
    return out;
  }

  /** ผู้เล่นพิมพ์แชทถึงบอท (ใส่ชื่อบอท) → บอทตอบ */
  replyTo(g, from, text) {
    const out = [];
    const lower = String(text).toLowerCase();
    for (const p of g.players) {
      if (!p.isBot || !p.alive || p.pid === from.pid) continue;
      if (lower.includes(p.name.toLowerCase())) { this.say(out, g, p, 'mentioned', { s: from }, 0.95, true); break; }
    }
    return out;
  }
}

